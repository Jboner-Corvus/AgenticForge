echo "3. Vérifiez vos permissions (Write/Admin)"
echo ""

echo "🛡️  ÉTAPE 3 : Vérification des branch protection rules"
echo "-----------------------------------------------------"
echo "1. Allez sur : https://github.com/Jboner-Corvus/AgenticForge/settings/branches"
