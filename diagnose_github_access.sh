    echo "💡 SOLUTION :"
    echo "1. Vérifiez d'abord vos tokens GitHub"
    echo "2. Si nécessaire, générez un nouveau token avec TOUS les scopes"
    echo "3. Vérifiez les paramètres du repository"
    echo ""
    echo "Nouveau token recommandé avec scopes : repo, workflow, delete_repo"
else
    echo "🔍 Problème plus subtil..."
    echo "Essayons une approche différente."
    echo ""
    echo "💡 SOLUTION ALTERNATIVE :"
    echo "1. Essayez de cloner le repository dans un nouveau dossier"
    echo "2. Comparez la configuration Git"
    echo "3. Vérifiez s'il y a des différences dans les credentials"
