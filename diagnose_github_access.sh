echo "🔍 DIAGNOSTIC COMPLET DE L'ACCÈS GITHUB"
echo "======================================"
echo ""

echo "📋 ÉTAPE 1 : Vérification des tokens"
echo "-----------------------------------"
echo "1. Allez sur : https://github.com/settings/tokens"
echo "2. Vérifiez si vos tokens sont toujours valides"
